// Импортируем основные типы Rapier 3D: физический мир, тела, коллайдеры и векторы.
use rapier3d::prelude::*;
// Импортируем описание демо и нативное окно визуализации Rapier Testbed.
use rapier_testbed3d::{ExampleEntry, TestbedViewer};

// Этот атрибут подготавливает асинхронный цикл нативного окна Kiss3d.
#[kiss3d::main]
// Главная асинхронная функция — с неё начинается выполнение программы.
pub async fn main() {
    // Создаём окно визуализатора и регистрируем в его интерфейсе одно демо.
    let mut viewer = TestbedViewer::new(vec![ExampleEntry::new("Demo", "Прыгающий шар")]).await;

    let mut world = create_world();
    // Передаём созданный физический мир визуализатору для построения объектов сцены.
    viewer.set_world(&mut world);
    // Ставим камеру в точку (10, 7, 15) и направляем её на точку (0, 4, 0).
    viewer.look_at(
        // Позиция камеры в трёхмерном мире.
        Vector::new(10.0, 7.0, 15.0),
        // Точка, на которую смотрит камера.
        Vector::new(0.0, 4.0, 0.0),
    );

    // Отрисовываем кадры, пока пользователь не закроет окно визуализатора.
    while viewer.render_frame(&mut world).await {
        // Проверяем состояние кнопок Play, Pause и Step в интерфейсе Testbed.
        if viewer.simulating() {
            // Продвигаем физический мир на один фиксированный временной шаг.
            world.step();
        } // Завершаем проверку необходимости следующего шага симуляции.
    } // Завершаем цикл после закрытия окна.
} // Завершаем программу.
//

fn create_world() -> PhysicsWorld {
    // Создаём полный физический мир со стандартной гравитацией (0, -9.81, 0).
    // PhysicsWorld уже содержит pipeline, тела, коллайдеры, joints, broad/narrow phase и CCD.
    let mut world = PhysicsWorld::new();

    // Добавляем неподвижное тело земли и его коллайдер с полуразмерами 100 × 0.1 × 100.
    world.insert(
        // Фиксированное тело не двигается и не падает под действием гравитации.
        RigidBodyBuilder::fixed(),
        // Полный размер земли получится равным 200 × 0.2 × 200 единиц.
        ColliderBuilder::cuboid(100.0, 0.1, 100.0),
    );

    // Добавляем динамический шар вместе с его сферическим коллайдером.
    world.insert(
        // Динамическое тело двигается, падает и реагирует на столкновения.
        RigidBodyBuilder::dynamic()
            // Размещаем центр шара на высоте 10 единиц.
            .translation(Vector::new(0.0, 10.0, 0.0)),
        // Задаём радиус шара 0.5 и упругость 0.7, чтобы он отскакивал.
        ColliderBuilder::ball(0.5).restitution(0.7),
    );

    // Добавляем динамический шар вместе с его сферическим коллайдером.
    world.insert(
        // Динамическое тело двигается, падает и реагирует на столкновения.
        RigidBodyBuilder::dynamic()
            // Размещаем центр шара на высоте 10 единиц.
            .translation(Vector::new(0.0, 20.0, 0.0)),
        // Задаём радиус шара 0.5 и упругость 0.7, чтобы он отскакивал.
        ColliderBuilder::ball(0.5).restitution(2.),
    );
    world
}
